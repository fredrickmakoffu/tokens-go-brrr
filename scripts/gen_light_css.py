#!/usr/bin/env python3
"""Regenerate the light-theme block of the extension's stylesheet.css.

St's CSS has no var(), so the popover's colours are literals. The dark values
stay as written; this reads every popover rule that carries a colour and emits
an override under .ai-usage-light with the matching light value (the website's
paper/ink tokens). The block sits between the two marker comments and is
replaced in place, so editing a dark rule and rerunning keeps both in step.

    python3 scripts/gen_light_css.py
"""
import re
from pathlib import Path

CSS = Path("gnome-shell-extension/ai-usage@fredrickmakoffu.github.io/stylesheet.css")
BEGIN = "/* >>> light theme (generated by scripts/gen_light_css.py; do not edit) */"
END = "/* <<< light theme */"

COLOURS = {
    "#2b2b2d": "#f2f2f3",  # surface
    "#f5f5f8": "#1d1f20",  # text
    "#b7b7ba": "#5d5d60",  # muted text
    "#4b4b4e": "#cfcfd1",  # hairline
    "#363638": "#e9e9ea",  # row hover
    "#3d3d3f": "#e1e1e3",  # chip hover
    "#94bce3": "#5980a6",  # accent marks, borders, focus rings
    "#98989b": "#7a7a7d",  # chevrons, paused marks
}
RGBA = {  # snow tint -> ink tint, steel tint -> darker steel tint
    "rgba(245, 245, 248,": "rgba(29, 31, 32,",
    "rgba(148, 188, 227,": "rgba(89, 128, 166,",
}
PRIMARY = {"#94bce3": "#416180", "#7fa6cc": "#375270", "#6890b5": "#2c455d", "#1d1f20": "#f2f2f3", "#f5f5f8": "#1d1f20"}
SHADOW = ("rgba(0, 0, 0, 0.35)", "rgba(29, 31, 32, 0.22)")
# Top-bar pieces sit on GNOME's own (always dark) panel, so they never change.
TOPBAR = re.compile(r"\.ai-usage-(dot|session-(icon|pct|count|stack|via)\b|sessions\s*$|session\s*$)")

HEX = re.compile(r"#[0-9a-fA-F]{6}\b|rgba?\([^)]*\)")


def light(decl: str, primary: bool) -> str | None:
    table = PRIMARY if primary else COLOURS
    changed = False

    def swap(m):
        nonlocal changed
        v = m.group(0)
        if v.startswith("rgba"):
            if v == SHADOW[0]:
                changed = True
                return SHADOW[1]
            for a, b in RGBA.items():
                if v.startswith(a):
                    changed = True
                    return b + v[len(a):]
            return v
        if v.lower() in table:
            changed = True
            return table[v.lower()]
        return v

    out = HEX.sub(swap, decl)
    return out if changed else None


def scope(selector: str) -> str:
    sel = selector.strip()
    if sel.startswith(".ai-usage-menu .popup-menu-content"):
        return ".ai-usage-menu.ai-usage-light" + sel[len(".ai-usage-menu"):]
    if sel.startswith(".ai-usage-menu "):
        sel = sel[len(".ai-usage-menu "):]
    return ".ai-usage-light " + sel


def main():
    text = CSS.read_text()
    if BEGIN in text:
        text = text[: text.index(BEGIN)].rstrip() + "\n"
    body = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out = []
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", body):
        sels = [s.strip() for s in m.group(1).split(",") if s.strip()]
        sels = [s for s in sels if not TOPBAR.search(s) and "#panel" not in s]
        if not sels:
            continue
        primary = any(s.startswith(".ai-usage-primary-btn") for s in sels)
        decls = []
        for d in m.group(2).split(";"):
            d = d.strip()
            if d and ":" in d:
                new = light(d, primary)
                if new:
                    decls.append(new + ";")
        if decls:
            out.append(",\n".join(scope(s) for s in sels) + " {\n  " + "\n  ".join(decls) + "\n}")
    block = (
        "\n\n" + BEGIN + "\n"
        "/* Applied by extension.js when GNOME's color-scheme is prefer-light. */\n"
        + "\n".join(out) + "\n" + END + "\n"
    )
    CSS.write_text(text + block)
    print(f"{len(out)} light rules written")


main()
