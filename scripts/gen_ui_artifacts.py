#!/usr/bin/env python3
"""Generate panel artifacts from ui/tokens.json.

Writes:
  - plasma/.../contents/ui/Tokens.qml  (QtObject singleton colours)
  - refreshes the GNOME light CSS block via gen_light_css logic

    python3 scripts/gen_ui_artifacts.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS_PATH = ROOT / "ui" / "tokens.json"
CSS = ROOT / "gnome-shell-extension" / "tokens-go-brrr@fredrickmakoffu.github.io" / "stylesheet.css"
TOKENS_QML = (
    ROOT / "plasma" / "org.tokensgobrrr.panel" / "contents" / "ui" / "Tokens.qml"
)
BEGIN = "/* >>> light theme (generated by scripts/gen_light_css.py; do not edit) */"
END = "/* <<< light theme */"

TOPBAR = re.compile(
    r"\.tokens-go-brrr-(dot|session-(icon|pct|count|stack|via)\b|sessions\s*$|session\s*$)"
)
HEX = re.compile(r"#[0-9a-fA-F]{6}\b|rgba?\([^)]*\)")


def load_tokens() -> dict:
    return json.loads(TOKENS_PATH.read_text())


def write_tokens_qml(tokens: dict) -> None:
    dark = tokens["dark"]
    light = tokens["light"]
    th = tokens["thresholds"]
    lines = [
        "// Generated by scripts/gen_ui_artifacts.py from ui/tokens.json — do not edit.",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        f"    readonly property int popoverWidth: {tokens['popoverWidthPx']}",
        f"    readonly property int dotSize: {tokens['dotPx']}",
        f"    readonly property int cautionAt: {th['cautionAt']}",
        f"    readonly property int criticalAt: {th['criticalAt']}",
        f'    readonly property string fontFamily: "{tokens["fontFamily"]}"',
        f'    readonly property string fontCondensed: "{tokens["fontFamilyCondensed"]}"',
        "",
        "    property bool light: false",
        "",
        "    readonly property color surface: light ? _light.surface : _dark.surface",
        "    readonly property color text: light ? _light.text : _dark.text",
        "    readonly property color mutedText: light ? _light.mutedText : _dark.mutedText",
        "    readonly property color hairline: light ? _light.hairline : _dark.hairline",
        "    readonly property color rowHover: light ? _light.rowHover : _dark.rowHover",
        "    readonly property color accent: light ? _light.accent : _dark.accent",
        "    readonly property color chevron: light ? _light.chevron : _dark.chevron",
        "    readonly property color ok: light ? _light.ok : _dark.ok",
        "    readonly property color wait: light ? _light.wait : _dark.wait",
        "    readonly property color crit: light ? _light.crit : _dark.crit",
        "    readonly property color error: light ? _light.error : _dark.error",
        "    readonly property color muted: light ? _light.muted : _dark.muted",
        "",
        "    readonly property QtObject _dark: QtObject {",
    ]
    for key in (
        "surface",
        "text",
        "mutedText",
        "hairline",
        "rowHover",
        "accent",
        "chevron",
        "ok",
        "wait",
        "crit",
        "error",
        "muted",
    ):
        lines.append(f'        readonly property color {key}: "{dark[key]}"')
    lines.append("    }")
    lines.append("")
    lines.append("    readonly property QtObject _light: QtObject {")
    for key in (
        "surface",
        "text",
        "mutedText",
        "hairline",
        "rowHover",
        "accent",
        "chevron",
        "ok",
        "wait",
        "crit",
        "error",
        "muted",
    ):
        lines.append(f'        readonly property color {key}: "{light[key]}"')
    lines.append("    }")
    lines.append("}")
    lines.append("")
    TOKENS_QML.parent.mkdir(parents=True, exist_ok=True)
    TOKENS_QML.write_text("\n".join(lines))


def light_decl(decl: str, primary: bool, tokens: dict) -> str | None:
    table = tokens["primaryLightMap"] if primary else tokens["lightMap"]
    rgba = tokens["rgbaLightPrefixes"]
    shadow = (tokens["dark"]["shadow"], tokens["light"]["shadow"])
    changed = False

    def swap(m: re.Match[str]) -> str:
        nonlocal changed
        v = m.group(0)
        if v.startswith("rgba"):
            if v == shadow[0]:
                changed = True
                return shadow[1]
            for a, b in rgba.items():
                if v.startswith(a):
                    changed = True
                    return b + v[len(a) :]
            return v
        if v.lower() in table:
            changed = True
            return table[v.lower()]
        return v

    out = HEX.sub(swap, decl)
    return out if changed else None


def scope(selector: str) -> str:
    sel = selector.strip()
    if sel.startswith(".tokens-go-brrr-menu .popup-menu-content"):
        return ".tokens-go-brrr-menu.tokens-go-brrr-light" + sel[len(".tokens-go-brrr-menu") :]
    if sel.startswith(".tokens-go-brrr-menu "):
        sel = sel[len(".tokens-go-brrr-menu ") :]
    return ".tokens-go-brrr-light " + sel


def write_light_css(tokens: dict) -> int:
    text = CSS.read_text()
    if BEGIN in text:
        text = text[: text.index(BEGIN)].rstrip() + "\n"
    body = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out: list[str] = []
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", body):
        sels = [s.strip() for s in m.group(1).split(",") if s.strip()]
        sels = [s for s in sels if not TOPBAR.search(s) and "#panel" not in s]
        if not sels:
            continue
        primary = any(s.startswith(".tokens-go-brrr-primary-btn") for s in sels)
        decls = []
        for d in m.group(2).split(";"):
            d = d.strip()
            if d and ":" in d:
                new = light_decl(d, primary, tokens)
                if new:
                    decls.append(new + ";")
        if decls:
            out.append(",\n".join(scope(s) for s in sels) + " {\n  " + "\n  ".join(decls) + "\n}")
    block = (
        "\n\n"
        + BEGIN
        + "\n"
        + "/* Applied by extension.js when GNOME's color-scheme is prefer-light. */\n"
        + "/* Colour maps from ui/tokens.json via scripts/gen_ui_artifacts.py. */\n"
        + "\n".join(out)
        + "\n"
        + END
        + "\n"
    )
    CSS.write_text(text + block)
    return len(out)


def main() -> int:
    tokens = load_tokens()
    write_tokens_qml(tokens)
    n = write_light_css(tokens)
    print(f"Tokens.qml written; {n} light CSS rules")
    return 0


if __name__ == "__main__":
    sys.exit(main())
